-- ----------------------------------------------------------------------------
-- 0. Vorhandene Objekte bereinigen (Idempotenz)
-- ----------------------------------------------------------------------------
BEGIN
   FOR c IN (SELECT table_name FROM user_tables 
             WHERE table_name IN ('AUDIT_LOG', 'OFFENDER_INVOLVEMENT', 'VICTIM_INVOLVEMENT', 
                                  'INCIDENT', 'AGENCY', 'PERSON', 'WEAPON', 'CIRCUMSTANCE')) LOOP
      EXECUTE IMMEDIATE 'DROP TABLE ' || c.table_name || ' CASCADE CONSTRAINTS PURGE';
   END LOOP;
EXCEPTION
   WHEN OTHERS THEN NULL;
END;
/

-- ----------------------------------------------------------------------------
-- 1. Tabelle: AGENCY (Polizeibehörde / Meldebehörde)
-- ----------------------------------------------------------------------------
CREATE TABLE agency (
    ori_code        VARCHAR2(7)   NOT NULL,
    agency_name     VARCHAR2(100) NOT NULL,
    state_name      VARCHAR2(50)  NOT NULL,
    population      NUMBER(10)    DEFAULT 0 NOT NULL,
    county          VARCHAR2(50),
    CONSTRAINT pk_agency PRIMARY KEY (ori_code),
    CONSTRAINT chk_agency_ori_len CHECK (LENGTH(ori_code) = 7),
    CONSTRAINT chk_agency_population CHECK (population >= 0)
);

-- ----------------------------------------------------------------------------
-- 2. Tabelle: PERSON (Beteiligte Personen: Opfer oder Täter)
-- ----------------------------------------------------------------------------
CREATE TABLE person (
    person_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1),
    age             NUMBER(3),
    sex             CHAR(1)       DEFAULT 'U' NOT NULL,
    race            VARCHAR2(50)  DEFAULT 'Unknown' NOT NULL,
    ethnicity       VARCHAR2(50)  DEFAULT 'Unknown' NOT NULL,
    CONSTRAINT pk_person PRIMARY KEY (person_id),
    CONSTRAINT chk_person_age CHECK (age IS NULL OR (age >= 0 AND age <= 120)),
    CONSTRAINT chk_person_sex CHECK (sex IN ('M', 'F', 'U')),
    CONSTRAINT chk_person_race CHECK (race IN ('White', 'Black', 'American Indian or Alaskan Native', 'Asian or Pacific Islander', 'Unknown')),
    CONSTRAINT chk_person_ethnicity CHECK (ethnicity IN ('Hispanic Origin', 'Not of Hispanic Origin', 'Unknown'))
);

-- ----------------------------------------------------------------------------
-- 3. Tabelle: WEAPON (Tatwaffen-Katalog)
-- ----------------------------------------------------------------------------
CREATE TABLE weapon (
    weapon_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1),
    weapon_code     VARCHAR2(10),
    description     VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_weapon PRIMARY KEY (weapon_id),
    CONSTRAINT uq_weapon_desc UNIQUE (description)
);

-- ----------------------------------------------------------------------------
-- 4. Tabelle: CIRCUMSTANCE (Tatumstände-Katalog)
-- ----------------------------------------------------------------------------
CREATE TABLE circumstance (
    circumstance_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1),
    circumstance_code VARCHAR2(10),
    description       VARCHAR2(150) NOT NULL,
    CONSTRAINT pk_circumstance PRIMARY KEY (circumstance_id),
    CONSTRAINT uq_circ_desc UNIQUE (description)
);

-- ----------------------------------------------------------------------------
-- 5. Tabelle: INCIDENT (Haupttabelle: Tötungsvorfälle)
-- ----------------------------------------------------------------------------
CREATE TABLE incident (
    incident_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1),
    ori_code          VARCHAR2(7)   NOT NULL,
    incident_year     NUMBER(4)     NOT NULL,
    incident_month    NUMBER(2)     NOT NULL,
    incident_number   VARCHAR2(20)  NOT NULL,
    situation         VARCHAR2(60)  DEFAULT 'Single Victim/Single Offender' NOT NULL,
    homicide_type     VARCHAR2(60)  DEFAULT 'Murder and Nonnegligent Manslaughter' NOT NULL,
    victim_count      NUMBER(3)     DEFAULT 1 NOT NULL,
    offender_count    NUMBER(3)     DEFAULT 1 NOT NULL,
    incident_date     DATE          NOT NULL,
    CONSTRAINT pk_incident PRIMARY KEY (incident_id),
    CONSTRAINT fk_incident_agency FOREIGN KEY (ori_code) REFERENCES agency(ori_code) ON DELETE CASCADE,
    CONSTRAINT uq_incident_case UNIQUE (ori_code, incident_year, incident_month, incident_number),
    CONSTRAINT chk_incident_year CHECK (incident_year BETWEEN 1900 AND 2100),
    CONSTRAINT chk_incident_month CHECK (incident_month BETWEEN 1 AND 12),
    CONSTRAINT chk_incident_vic_cnt CHECK (victim_count >= 1),
    CONSTRAINT chk_incident_off_cnt CHECK (offender_count >= 0),
    CONSTRAINT chk_incident_situation CHECK (situation IN (
        'Single Victim/Single Offender',
        'Single Victim/Unknown Offender(s)',
        'Single Victim/Multiple Offenders',
        'Multiple Victims/Single Offender',
        'Multiple Victims/Multiple Offenders',
        'Multiple Victims/Unknown Offender(s)'
    )),
    CONSTRAINT chk_incident_hom_type CHECK (homicide_type IN (
        'Murder and Nonnegligent Manslaughter',
        'Manslaughter by Negligence'
    ))
);

-- ----------------------------------------------------------------------------
-- 6. Tabelle: VICTIM_INVOLVEMENT (1. m:n-Zuordnung: INCIDENT <-> PERSON)
-- ----------------------------------------------------------------------------
CREATE TABLE victim_involvement (
    incident_id       NUMBER        NOT NULL,
    person_id         NUMBER        NOT NULL,
    victim_sequence   NUMBER(2)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_victim_involvement PRIMARY KEY (incident_id, person_id),
    CONSTRAINT fk_vi_incident FOREIGN KEY (incident_id) REFERENCES incident(incident_id) ON DELETE CASCADE,
    CONSTRAINT fk_vi_person FOREIGN KEY (person_id) REFERENCES person(person_id) ON DELETE CASCADE,
    CONSTRAINT chk_vi_sequence CHECK (victim_sequence >= 1)
);

-- ----------------------------------------------------------------------------
-- 7. Tabelle: OFFENDER_INVOLVEMENT (2. m:n-Zuordnung: INCIDENT <-> PERSON)
-- ----------------------------------------------------------------------------
CREATE TABLE offender_involvement (
    incident_id       NUMBER        NOT NULL,
    person_id         NUMBER        NOT NULL,
    victim_person_id  NUMBER,
    weapon_id         NUMBER        NOT NULL,
    circumstance_id   NUMBER        NOT NULL,
    relationship      VARCHAR2(60)  DEFAULT 'Unknown Relationship' NOT NULL,
    offender_sequence NUMBER(2)     DEFAULT 1 NOT NULL,
    CONSTRAINT pk_offender_involvement PRIMARY KEY (incident_id, person_id),
    CONSTRAINT fk_oi_incident FOREIGN KEY (incident_id) REFERENCES incident(incident_id) ON DELETE CASCADE,
    CONSTRAINT fk_oi_person FOREIGN KEY (person_id) REFERENCES person(person_id) ON DELETE CASCADE,
    CONSTRAINT fk_oi_victim FOREIGN KEY (victim_person_id) REFERENCES person(person_id) ON DELETE SET NULL,
    CONSTRAINT fk_oi_weapon FOREIGN KEY (weapon_id) REFERENCES weapon(weapon_id),
    CONSTRAINT fk_oi_circ FOREIGN KEY (circumstance_id) REFERENCES circumstance(circumstance_id),
    CONSTRAINT chk_oi_sequence CHECK (offender_sequence >= 1)
);

-- ----------------------------------------------------------------------------
-- 8. Tabelle: AUDIT_LOG (Eigene Tabelle für After-Update-Trigger)
-- ----------------------------------------------------------------------------
CREATE TABLE audit_log (
    log_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 INCREMENT BY 1),
    incident_id       NUMBER        NOT NULL,
    old_situation     VARCHAR2(60),
    new_situation     VARCHAR2(60)  NOT NULL,
    changed_by        VARCHAR2(100) DEFAULT USER NOT NULL,
    changed_at        TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    action_type       VARCHAR2(20)  DEFAULT 'UPDATE' NOT NULL,
    CONSTRAINT pk_audit_log PRIMARY KEY (log_id),
    CONSTRAINT fk_audit_incident FOREIGN KEY (incident_id) REFERENCES incident(incident_id) ON DELETE CASCADE,
    CONSTRAINT chk_audit_action CHECK (action_type IN ('INSERT', 'UPDATE', 'DELETE'))
);
